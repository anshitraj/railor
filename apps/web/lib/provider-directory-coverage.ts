const corridorMap = new Map<string, MappedProviderCoverage>();
for (const provider of corridorDiscovery.providers) {
  const countries = new Set<string>();
  const currencies = new Set<string>();
  const customerTypes = new Set<string>();
  for (const route of provider.routes) {
    if (route.origin) countries.add(route.origin);
    if (route.destination) countries.add(route.destination);
    if (route.from) currencies.add(route.from);
    if (route.to) currencies.add(route.to);
    for (const profile of route.profiles) {
      customerTypes.add(profile === "personal" ? "individual" : "business");
    }
  }
  corridorMap.set(provider.slug, {
    countries: [...countries],
    currencies: [...currencies],
    products: ["payout"],
    customerTypes: [...customerTypes],
    summary: provider.pricingNote,
    sourceUrl: provider.sources[0] ?? provider.website,
  });
}

const reviewSummaryBySlug = new Map(pricingReview.providers.map((entry) => [entry.slug, entry]));

/** Returns verified coverage metadata for any slug (infrastructure, corridor discovery or transfer directory). */
export function directoryCoverageFor(slug: string): MappedProviderCoverage | null {
  const key = slug.toLowerCase();
  const explicit = VERIFIED_PROVIDER_COVERAGE[key];
  const corridor = corridorMap.get(key);
  if (!explicit && !corridor) return null;
  if (!explicit) return corridor!;
  if (!corridor) return explicit;
  return {
    ...explicit,
    countries: [...new Set([...explicit.countries, ...corridor.countries])],
    currencies: [...new Set([...explicit.currencies, ...corridor.currencies])],
    customerTypes: [...new Set([...(explicit.customerTypes ?? []), ...(corridor.customerTypes ?? [])])],
    summary: explicit.summary ?? corridor.summary,
    sourceUrl: explicit.sourceUrl ?? corridor.sourceUrl,
  };
}

/**
 * Enriches a DirectoryProvider row with verified official-domain coverage,
 * products, API flags and published pricing summary whenever the DB/directory
 * row lacks mapped counts.
 */
export function enrichDirectoryProvider(provider: DirectoryProvider): DirectoryProvider {
  const mapped = directoryCoverageFor(provider.slug);
  const facts = providerFacts(provider.slug, { from: "USD", to: "EUR" });
  const review = reviewSummaryBySlug.get(provider.slug);
  const countryCount = Math.max(provider.countryCount, mapped?.countries.length ?? 0);
  const currencyCount = Math.max(provider.currencyCount, mapped?.currencies.length ?? 0);
  const products = provider.products.length ? provider.products : (mapped?.products ?? []);
  const assets = provider.assets.length ? provider.assets : (mapped?.assets ?? []);
  const customerTypes = provider.customerTypes.length ? provider.customerTypes : (mapped?.customerTypes ?? []);
  const pricingSummary = provider.pricingSummary
    ?? facts?.fees?.lines[0]
    ?? mapped?.summary
    ?? review?.summary
    ?? undefined;
  const description = provider.description && !provider.description.startsWith("Check the provider’s website")
    ? provider.description
    : (mapped?.summary ?? facts?.fees?.lines[0] ?? provider.description);
  const sourceUrl = provider.sourceUrl ?? mapped?.sourceUrl ?? review?.sourceUrl ?? providerSite(provider.slug) ?? undefined;
  return {
    ...provider,
    description,
    products,
    assets,
    customerTypes,
    countryCount,
    currencyCount,
    scopeLabel: provider.scopeLabel ?? (countryCount === 0 ? mapped?.scopeLabel : undefined),
    hasApi: provider.hasApi || Boolean(mapped?.hasApi),
    hasSandbox: provider.hasSandbox || Boolean(mapped?.hasSandbox),
    lastVerifiedAt: provider.lastVerifiedAt ?? (mapped ? REVIEWED_DATE : null),
    pricingSummary,
    sourceUrl,
  };
}
